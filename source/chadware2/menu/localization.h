// Translate a UI string for the active language (falls back to the English text).
inline const char* tr(const char* english)
{
    if (g_Language != 1 || !english)
        return english;

    const auto& table = Localization::Russian();
    const auto it = table.find(english);
    return it != table.end() ? it->second : english;
}
